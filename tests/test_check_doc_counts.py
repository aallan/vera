def _run_main(
    monkeypatch: pytest.MonkeyPatch,
    argv: list[str],
    *,
    stale: list[str] | None = None,
    mode: tuple[bool, str] | Exception | None = None,
) -> tuple[int, list[Path]]:
    """`main()` with render_status's answer and the release-mode answer
    stubbed; returns the exit code and the roots the freshness check was
    asked about."""
    asked: list[Path] = []

    def stale_blocks(root: Path) -> list[str]:
        asked.append(root)
        return list(stale or [])

    monkeypatch.setattr(
        _MOD, "_render_status",
        lambda: types.SimpleNamespace(stale_blocks=stale_blocks),
    )
    if mode is not None:
        def release_mode_for(base: str, root: Path) -> tuple[bool, str]:
            if isinstance(mode, Exception):
                raise mode
            return mode

        monkeypatch.setattr(_MOD, "release_mode_for", release_mode_for)
    monkeypatch.setattr(sys, "argv", ["check_doc_counts.py", *argv])
    monkeypatch.setattr(sys, "path", list(sys.path))
    return _MOD.main(), asked


class TestTheFreshnessCheck:
    def test_release_mode_fails_on_a_stale_status(
        self, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        stale = "TESTING.md: the generated `test-files` block is not current"
        code, asked = _run_main(monkeypatch, ["--release"], stale=[stale])
        assert code == 1
        assert asked == [_SCRIPT.resolve().parent.parent]
        assert stale in capsys.readouterr().err

    def test_release_mode_passes_a_current_status(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        code, asked = _run_main(monkeypatch, ["--release"], stale=[])
        assert (code, len(asked)) == (0, 1)

    def test_the_default_mode_reads_no_count(
        self, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """A fix PR's run: a status that has fallen behind the tree is not
        an error between releases, so the check is not even asked."""
        code, asked = _run_main(monkeypatch, [], stale=["stale"])
        assert (code, asked) == (0, [])
        assert "--release" in capsys.readouterr().out

    def test_it_reaches_the_real_generator(self, tmp_path: Path) -> None:
        """No stubs: the script loads render_status.py from beside itself
        and returns its answer — here, that a document without the
        markers cannot be checked."""
        (tmp_path / "TESTING.md").write_text("# Testing\n", encoding="utf-8")
        (error,) = _MOD.stale_status(tmp_path)
        assert "render_status:begin status" in error


