class TestCheckBugIssues:
    """`--check-bug-issues` as the release PR runs it: the file read, the
    tracker queried (stubbed here), and every way the two disagree
    reported."""

    def _check(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
        text: str, tracker: list[int] | Exception,
    ) -> list[str]:
        (tmp_path / "KNOWN_ISSUES.md").write_text(text, encoding="utf-8")

        def open_bug_issues() -> list[int]:
            if isinstance(tracker, Exception):
                raise tracker
            return tracker

        monkeypatch.setattr(_MOD, "open_bug_issues", open_bug_issues)
        errors: list[str] = _MOD.check_bug_issues(tmp_path)
        return errors

    def test_an_agreeing_table_is_clean(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        assert self._check(tmp_path, monkeypatch, _bugs(_row(1), _row(2)), [2, 1]) == []

    def test_two_rows_for_one_issue_are_an_error(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """One-to-one: a duplicate row is not two bugs, though the sets agree."""
        errors = self._check(
            tmp_path, monkeypatch, _bugs(_row(1), _row(1, "Again.")), [1],
        )
        assert errors == ["KNOWN_ISSUES.md: issue #1 has a Bugs row twice"]

    def test_an_unreadable_table_is_an_error_not_a_skip(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        errors = self._check(
            tmp_path, monkeypatch, _bugs_section("| Bug | Issue |\n|-----|-------|"), [1],
        )
        assert len(errors) == 1 and "cannot be read" in errors[0]

    def test_a_failed_query_is_an_error(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        errors = self._check(
            tmp_path, monkeypatch, _bugs(_row(1)), _MOD.BugQueryError("offline"),
        )
        assert errors == ["KNOWN_ISSUES.md: offline"]

    def test_the_tracker_is_asked_only_when_the_flag_says_so(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A run without `--check-bug-issues` makes no network call."""
        def no_network() -> list[int]:
            raise AssertionError("the GitHub API was queried")

        monkeypatch.setattr(_MOD, "open_bug_issues", no_network)
        for argv in ([], ["--release"]):
            code, _asked = _run_main(monkeypatch, argv, stale=[])
            assert code == 0, argv
