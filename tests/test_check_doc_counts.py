"""scripts/check_doc_counts.py, the documentation's release-time checks.

No gate compares two hand-written copies of a count: TESTING.md's status is
generated by scripts/render_status.py (tests/test_render_status.py), and
this script asks, at release, whether it is what that script writes now.
Release mode is chosen from the version bump (#1536), and ``--print-release-
mode`` answers the same question for ci.yml's plan job.  The one check that
needs the GitHub API, KNOWN_ISSUES.md's Bugs table against the open
`bug`-labelled issues, is opt-in.
"""

from __future__ import annotations

import importlib.util
import os
import re
import subprocess
import sys
import types
from pathlib import Path
from typing import Any

import pytest

_SCRIPT = Path(__file__).parent.parent / "scripts" / "check_doc_counts.py"


def _load() -> Any:
    spec = importlib.util.spec_from_file_location("check_doc_counts", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_MOD = _load()


