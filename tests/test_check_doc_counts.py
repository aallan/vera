_BUGS_DESCRIPTION = (
    "Defects in shipped compiler, runtime, or tooling behaviour — this"
    " table matches the issue tracker's open `bug`-labelled issues"
    " one-to-one."
)


def _bugs_section(body: str) -> str:
    """A KNOWN_ISSUES.md whose `## Bugs` section holds `body`."""
    return (
        f"# Known Issues\n\n## Bugs\n\n{_BUGS_DESCRIPTION}\n\n{body}\n\n"
        "## Limitations\n\n| Limitation | Issue |\n|-----------|-------|\n"
        "| Something missing. |"
        " [#900](https://github.com/aallan/vera/issues/900) |\n"
    )


def _bugs(*rows: str) -> str:
    body = "\n".join(rows)
    return _bugs_section(f"| Bug | Issue |\n|-----|-------|\n{body}")


def _row(number: int, text: str = "Something is wrong.") -> str:
    url = f"https://github.com/aallan/vera/issues/{number}"
    return f"| {text} | [#{number}]({url}) |"


class TestBugRows:
    """The reader the release-time parity check stands on."""

    def test_the_shipped_table_parses(self) -> None:
        text = (_SCRIPT.parent.parent / "KNOWN_ISSUES.md").read_text(encoding="utf-8")
        rows = _MOD.bug_rows(text)
        assert not isinstance(rows, str), rows
        section = re.search(r"^## Bugs[ \t]*$(.*?)(?=^## )", text, re.M | re.S)
        assert section is not None
        table = [
            line for line in section.group(1).splitlines()
            if line.startswith("|") and not set(line) <= set("|- ")
        ][1:]  # drop the header row
        assert len(rows) == len(table)

    def test_only_the_issue_column_is_read(self) -> None:
        """A row's prose cross-links other issues; only its last cell is
        its tracker, and a `|` in the prose cannot shift it."""
        text = _bugs(
            _row(101, "Like [#7](https://github.com/aallan/vera/issues/7), the `|>` is wrong."),
            _row(102),
        )
        assert _MOD.bug_rows(text) == [101, 102]

    @pytest.mark.parametrize(
        ("body", "reason"),
        [
            ("| Bug | Issue |\n|-----|-------|\n| No tracker. | none |", "exactly one"),
            ("| Bug | Issue |\n|-----|-------|\n"
             "| Mislinked. | [#101](https://github.com/aallan/vera/issues/202) |", "exactly one"),
            ("| Bug | Issue |\n|-----|-------|", "does not end with"),
            ("Some prose but no table and no marker.", "does not end with"),
            ("No known bugs.\n\nBut there is one.", "does not END with it"),
            (f"No known bugs.\n\n| Bug | Issue |\n|-----|-------|\n{_row(101)}", "both"),
        ],
        ids=["no link", "mislinked", "emptied table", "no marker",
             "text after the marker", "marker and table"],
    )
    def test_an_unreadable_table_is_a_reason(self, body: str, reason: str) -> None:
        read = _MOD.bug_rows(_bugs_section(body))
        assert isinstance(read, str) and reason in read, read

    def test_the_zero_form_is_read_beside_the_description(self) -> None:
        assert _MOD.bug_rows(_bugs_section("No known bugs.")) == []

    def test_a_renamed_heading_is_a_reason(self) -> None:
        assert isinstance(_MOD.bug_rows(_bugs(_row(101)).replace("## Bugs", "## Open")), str)


