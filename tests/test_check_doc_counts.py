def _make_fake_checkout(root: Path, marker: str) -> None:
    (root / "vera").mkdir(parents=True)
    (root / "vera" / "__init__.py").write_text(
        f'MARKER = "{marker}"\n', encoding="utf-8")
    (root / "scripts").mkdir()


class TestCrossCheckoutImportIsolation:
    """render_status.py imports `vera` in process; a script that inserts its
    own root at `sys.path[0]` before that import measures its own checkout,
    whatever `PYTHONPATH` or an editable install says."""

    def test_root_insertion_wins_over_a_stale_pythonpath(
        self, tmp_path: Path,
    ) -> None:
        _make_fake_checkout(tmp_path / "checkout_a", "A")
        _make_fake_checkout(tmp_path / "checkout_b", "B")
        probe = tmp_path / "checkout_a" / "scripts" / "probe.py"
        probe.write_text(
            "import sys\n"
            "from pathlib import Path\n"
            "root = Path(__file__).resolve().parent.parent\n"
            "sys.path.insert(0, str(root))\n"
            "import vera\n"
            "print(vera.MARKER)\n",
            encoding="utf-8",
        )
        env = dict(os.environ)
        env["PYTHONPATH"] = str(tmp_path / "checkout_b")
        result = subprocess.run(
            [sys.executable, str(probe)],
            capture_output=True, text=True, encoding="utf-8",
            env=env, check=False,
        )
        assert result.stdout.strip() == "A", result.stderr

    def test_without_the_fix_a_stale_pythonpath_wins(
        self, tmp_path: Path,
    ) -> None:
        """The negative control: without the insertion the same setup
        resolves the other checkout's package."""
        _make_fake_checkout(tmp_path / "checkout_a", "A")
        _make_fake_checkout(tmp_path / "checkout_b", "B")
        probe = tmp_path / "checkout_a" / "scripts" / "probe_unfixed.py"
        probe.write_text("import vera\nprint(vera.MARKER)\n", encoding="utf-8")
        env = dict(os.environ)
        env["PYTHONPATH"] = str(tmp_path / "checkout_b")
        result = subprocess.run(
            [sys.executable, str(probe)],
            capture_output=True, text=True, encoding="utf-8",
            env=env, check=False,
        )
        assert result.stdout.strip() == "B", result.stderr

    def test_main_inserts_root_before_the_freshness_check(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """`main()` puts its root first on `sys.path` before it asks
        render_status anything, so the generator's `vera` imports resolve
        to this checkout."""
        seen: list[str] = []

        def stale_blocks(root: Path) -> list[str]:
            seen.append(sys.path[0])
            return []

        monkeypatch.setattr(
            _MOD, "_render_status",
            lambda: types.SimpleNamespace(stale_blocks=stale_blocks),
        )
        monkeypatch.setattr(sys, "argv", ["check_doc_counts.py", "--release"])
        monkeypatch.setattr(sys, "path", ["/somewhere/else", *sys.path])
        assert _MOD.main() == 0
        assert seen == [str(_SCRIPT.resolve().parent.parent)]


